import Modal from '../../../../core/react-src/src/shared/Modal.jsx';
import RoleBadge from '../../../../core/react-src/src/shared/RoleBadge.jsx';

/* Справка по доступам.

   Половина текста собирается из живых порогов, а не написана руками: иначе
   она разойдётся с настройками в первый же раз, когда порог подвинут, и
   станет хуже, чем никакой. */

export default function Faq({ open, onClose, data }) {
  if (!open || !data) return null;

  const byRole = {};
  data.actions.forEach((a) => {
    (byRole[a.role] = byRole[a.role] || []).push(a.title);
  });

  return (
    <Modal open={open} title="Как устроены доступы" onClose={onClose} boxCls="adm-faq-modal">
      <div className="adm-faq">
        <p>
          <b>Ступени накопительные.</b> Каждая следующая добавляет к предыдущей
          и ничего не отнимает. Кто на пятой ступени, тот может всё, что можно
          на первых четырёх.
        </p>
        <p>
          <b>Ранг и раздел — разные вещи.</b> Ранг говорит, <i>что</i> человек
          умеет делать; выданный раздел — <i>где</i>. Нужно и то и другое:
          выдали «Серверы», но ступень не тянет — раздел не появится.
        </p>
        <p>
          <b>Раздел выдаётся по ступени.</b> Порог раздела равен порогу права
          его видеть. Поэтому «Серверы» нельзя выдать тому, кто их не увидит.
          Подняли порог — выдача у тех, кто перестал его тянуть, снимается
          сразу, и об этом говорится списком.
        </p>
        <p>
          <b>Подсказки в интерфейсе.</b> Где кнопка видна, но нажать нельзя —
          написано, какая ступень нужна. Где раздела или кнопки не видно вовсе,
          подсказки нет: человеку незачем знать о том, чего для него не
          существует.
        </p>
        <p>
          <b>Настройки этого окна</b> может менять только владелец
          (<RoleBadge role="arcana" />), и порог этой строки не двигается.
          Будь он изменяемым, любой, кому однажды открыли редактор, поднял бы
          себе права до владельца — вместе с созданием учёток.
        </p>

        <div className="adm-faq-title">Что открывает каждая ступень сейчас</div>
        {data.roles.map((r) => (
          <div className="adm-faq-step" key={r}>
            <RoleBadge role={r} />
            <span>{(byRole[r] || []).join(' · ') || '— ничего сверх предыдущей —'}</span>
          </div>
        ))}

        <div className="adm-faq-title">С какой ступени можно выдать раздел</div>
        <div className="adm-faq-mods">
          {Object.entries(data.modules).map(([m, r]) => (
            <div key={m}><b>{m}</b> — <RoleBadge role={r} /></div>
          ))}
        </div>
      </div>
    </Modal>
  );
}
